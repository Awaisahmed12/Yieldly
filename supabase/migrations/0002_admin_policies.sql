-- Admin write policies for static tables
-- Requires app_metadata.role = 'admin' set via Supabase dashboard or service-role API

CREATE POLICY "admin_all_banks"
  ON banks FOR ALL
  USING ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  WITH CHECK ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

